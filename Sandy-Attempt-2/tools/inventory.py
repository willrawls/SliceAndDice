"""Reproducible form/control inventory. Read only from Sandy; never consult attempt 1.

Keep every designer property and source handler name, including third-party controls.
FRX strings/lists are decoded; picture references retain their source offsets.
"""
import hashlib
import base64
import json
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parents[1]


def parse(path):
    raw = path.read_bytes()
    text = raw.decode('cp1252')
    stack, root, properties = [], None, []
    for line in text.splitlines():
        if line.startswith('Attribute '):
            break
        s = line.strip()
        if s.startswith('BeginProperty '):
            properties.append(s.split()[1])
        elif s == 'EndProperty':
            properties.pop()
        elif m := re.match(r'Begin (\S+) (\w+)', s):
            node = dict(type=m[1], name=m[2], properties={}, children=[])
            if stack:
                stack[-1]['children'].append(node)
            else:
                root = node
            stack.append(node)
        elif s == 'End' and stack:
            stack.pop()
        elif stack and (m := re.match(r'(\w+(?:\(\d+\))?)\s*=\s*(.*)', s)):
            value = m[2]
            if value.startswith('"'):
                match = re.match(r'"((?:[^"]|"")*)"(?::([0-9A-Fa-f]+))?', value)
                value = match[1].replace('""', '"') if match else value
                if match and match[2]:
                    value = {'file': value, 'offset': int(match[2], 16)}
            else:
                value = value.split("'", 1)[0].strip()
            key = '.'.join(properties + [m[1]])
            stack[-1]['properties'][key] = value
    if root is None or stack or properties:
        raise ValueError(f'Unbalanced designer: {path}')
    root['source'] = path.relative_to(ROOT).as_posix()
    root['sha256'] = hashlib.sha256(raw).hexdigest()
    root['handlers'] = re.findall(r'(?:Private|Public|Friend) Sub (\w+)\(', text)

    def decode(node):
        for key, value in list(node['properties'].items()):
            if isinstance(value, dict) and key in ('Picture', 'Icon'):
                data = (path.parent / value['file']).read_bytes()
                pos = value['offset']
                length = struct.unpack_from('<I', data, pos)[0]
                payload = data[pos+4:pos+4+length]
                signatures = [b'\x00\x00\x01\x00', b'BM', b'GIF8', b'\x89PNG', b'\xff\xd8\xff']
                matches = [payload.find(sig) for sig in signatures if 0 <= payload.find(sig) < 80]
                if matches:
                    node['properties'][key + 'Base64'] = base64.b64encode(payload[min(matches):]).decode('ascii')
            if not isinstance(value, dict) or key not in ('Text', 'Caption', 'List', 'ToolTipText'):
                continue
            data = (path.parent / value['file']).read_bytes()
            pos = value['offset']
            if key == 'List':
                count = struct.unpack_from('<H', data, pos)[0]
                pos += 4 if count else 2
                strings = []
                for _ in range(count):
                    length = struct.unpack_from('<H', data, pos)[0]
                    pos += 2
                    strings.append(data[pos:pos+length].decode('cp1252'))
                    pos += length
                node['properties']['Items'] = strings
            else:
                length = data[pos]
                pos += 1
                if length == 255:
                    length = struct.unpack_from('<H', data, pos)[0]
                    pos += 2
                node['properties'][key] = data[pos:pos+length].decode('cp1252')
        for child in node['children']:
            decode(child)
    decode(root)
    # Files reuse VB_Name: ShellMain and frmMain both call themselves frmMain.
    root['className'] = path.stem if path.parent.name != 'DataView' else 'DataViewForm1'
    return root


def main():
    forms = [parse(p) for p in sorted((ROOT / 'Sandy').rglob('*.frm'))]
    destination = OUT / 'src/Sandy.Desktop/Forms'
    (destination / 'catalog.json').write_text(json.dumps(forms, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    lines = ['// Generated by tools/inventory.py from Sandy/**/*.frm.', 'namespace Sandy.Desktop.Forms;', '']
    for form in forms:
        name = form['className']
        lines.append(f'public sealed class {name} : LegacyForm {{ public {name}() : base("{name}") {{ }} }}')
    (destination / 'Forms.g.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    sources = []
    missing = []
    for project in sorted((ROOT / 'Sandy').rglob('*.vbp')):
        for line in project.read_text(encoding='cp1252').splitlines():
            if line.startswith(('Class=', 'Module=', 'Form=', 'UserControl=')):
                relative = line.split('=', 1)[1].split(';')[-1].strip()
                if not (project.parent / relative).exists():
                    missing.append({'project': project.relative_to(ROOT).as_posix(), 'reference': relative})
    for path in sorted((ROOT / 'Sandy').rglob('*')):
        if path.is_file():
            sources.append({'path': path.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    (OUT / 'docs/source-inventory.json').write_text(json.dumps({'forms': len(forms), 'missingProjectReferences': missing, 'sources': sources}, indent=2) + '\n', encoding='utf-8')
    print(f'{len(forms)} forms; {len(sources)} source files; {len(missing)} unresolved VB project references')


if __name__ == '__main__':
    main()
